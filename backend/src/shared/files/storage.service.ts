import { createReadStream } from 'node:fs';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { type Readable } from 'node:stream';
import { randomBytes } from 'node:crypto';
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { HttpStatus, Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { type Env } from '../config/env';
import { AppException } from '../http/app-exception';

export type Visibility = 'public' | 'private';

export interface UploadedFile {
  buffer: Buffer;
  mimetype: string;
  size: number;
  originalname: string;
}

const EXT: Record<string, string> = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'application/pdf': 'pdf',
};

/** Checks real file signatures, not just the client-supplied MIME type. */
function sniff(buf: Buffer): string | null {
  if (buf.subarray(0, 3).equals(Buffer.from([0xff, 0xd8, 0xff]))) return 'image/jpeg';
  if (buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return 'image/png';
  if (buf.subarray(0, 4).toString() === 'RIFF' && buf.subarray(8, 12).toString() === 'WEBP') return 'image/webp';
  if (buf.subarray(0, 5).toString() === '%PDF-') return 'application/pdf';
  return null;
}

export const fileInvalid = (message: string) => new AppException(HttpStatus.BAD_REQUEST, 'FILE_INVALID', message);

/**
 * Two storage areas: public (place photos, served to anyone) and private (KYC documents, admin only).
 * Local driver: files on disk, public ones served by FilesController. S3 driver: two buckets.
 */
@Injectable()
export class StorageService {
  private readonly driver: 'local' | 's3';
  private readonly dir: string;
  private readonly s3?: S3Client;

  constructor(private readonly config: ConfigService<Env, true>) {
    this.driver = config.get('STORAGE_DRIVER', { infer: true });
    this.dir = resolve(config.get('STORAGE_DIR', { infer: true }));
    if (this.driver === 's3') {
      const keyId = config.get('S3_ACCESS_KEY_ID', { infer: true });
      const secret = config.get('S3_SECRET_ACCESS_KEY', { infer: true });
      this.s3 = new S3Client({
        region: config.get('S3_REGION', { infer: true }),
        endpoint: config.get('S3_ENDPOINT', { infer: true }) || undefined,
        forcePathStyle: !!config.get('S3_ENDPOINT', { infer: true }),
        credentials: keyId && secret ? { accessKeyId: keyId, secretAccessKey: secret } : undefined,
      });
    }
  }

  /** Validate type/size, then store. Returns the storage key. */
  async save(
    visibility: Visibility,
    prefix: string,
    file: UploadedFile | undefined,
    opts: { allowed: string[]; maxBytes: number },
  ): Promise<{ key: string; contentType: string }> {
    if (!file?.buffer?.length) throw fileInvalid('Choose a file to upload');
    if (file.size > opts.maxBytes) throw fileInvalid(`File is too large (max ${Math.round(opts.maxBytes / 1_048_576)} MB)`);
    const contentType = sniff(file.buffer);
    if (!contentType || !opts.allowed.includes(contentType)) {
      throw fileInvalid(`Unsupported file type. Allowed: ${opts.allowed.map((t) => EXT[t]).join(', ')}`);
    }
    const key = `${prefix}/${Date.now()}-${randomBytes(8).toString('hex')}.${EXT[contentType]}`;
    if (this.s3) {
      await this.s3.send(
        new PutObjectCommand({ Bucket: this.bucket(visibility), Key: key, Body: file.buffer, ContentType: contentType }),
      );
    } else {
      const path = this.localPath(visibility, key);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, file.buffer);
    }
    return { key, contentType };
  }

  /** Browser URL of a public file. Local URLs are relative so they work through the web proxy. */
  publicUrl(key: string): string {
    return this.s3 ? `${this.config.get('S3_PUBLIC_URL', { infer: true })!.replace(/\/$/, '')}/${key}` : `/api/v1/files/${key}`;
  }

  async read(visibility: Visibility, key: string): Promise<Readable> {
    if (this.s3) {
      const res = await this.s3.send(new GetObjectCommand({ Bucket: this.bucket(visibility), Key: key }));
      return res.Body as Readable;
    }
    return createReadStream(this.localPath(visibility, key));
  }

  async remove(visibility: Visibility, key: string): Promise<void> {
    if (this.s3) await this.s3.send(new DeleteObjectCommand({ Bucket: this.bucket(visibility), Key: key }));
    else await rm(this.localPath(visibility, key), { force: true });
  }

  /** Rejects path traversal: keys are generated by save() and only contain [a-z0-9/._-]. */
  localPath(visibility: Visibility, key: string): string {
    if (!/^[a-z0-9-]+(\/[a-zA-Z0-9._-]+)+$/.test(key) || key.includes('..')) throw fileInvalid('Bad file key');
    return join(this.dir, visibility, key);
  }

  private bucket(v: Visibility) {
    return this.config.get(v === 'public' ? 'S3_PUBLIC_BUCKET' : 'S3_PRIVATE_BUCKET', { infer: true })!;
  }
}

export const IMAGE_TYPES = ['image/jpeg', 'image/png', 'image/webp'];
export const DOC_TYPES = [...IMAGE_TYPES, 'application/pdf'];
export const MAX_UPLOAD_BYTES = 5 * 1_048_576;
